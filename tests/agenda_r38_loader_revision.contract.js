'use strict';
const fs=require('fs');
const assert=require('assert');
const loader=fs.readFileSync('src/ui/screen_loader-1.25.0.js','utf8');
const html=fs.readFileSync('index.html','utf8');
const revision=loader.match(/ASSET_REVISION=['"]([^'"]+)['"]/)?.[1];
assert(revision,'loader deve declarar revisão de cache');
const src=html.match(/src="(src\/ui\/screen_loader-1\.25\.0\.js\?[^\"]+)"/)?.[1];
assert(src,'index deve invalidar o cache do loader');
assert.equal(new URL(src,'https://kinesys.example').searchParams.get('v'),revision,'index e loader devem usar a revisão atual, sem congelar uma versão antiga');
assert.match(loader,/agenda_mobile_order-1\.0\.0\.css\?v=[^'"\s]+/);
assert.match(loader,/agenda_lifecycle-1\.0\.0\.js\?v=[^'"\s]+/);
console.log('Agenda r38 loader revision contract OK.');
