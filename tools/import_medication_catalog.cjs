'use strict';
// Reproducible, offline import. Never reads patient records or modifies the source CSV.
const fs=require('node:fs'),crypto=require('node:crypto');
const SOURCE_URL='https://dados.anvisa.gov.br/dados/DADOS_ABERTOS_MEDICAMENTOS.csv';
const normalize=s=>String(s||'').normalize('NFD').replace(/[\u0300-\u036f]/g,'').toLowerCase().replace(/\s+/g,' ').trim();
const clean=s=>String(s||'').replace(/\s+/g,' ').trim();
function parseCsv(text){
 const rows=[];let row=[],cell='',quoted=false;
 for(let i=0;i<text.length;i++){
  const c=text[i];
  if(c==='"'){if(quoted&&text[i+1]==='"'){cell+='"';i++;}else quoted=!quoted;}
  else if(!quoted&&(c===';'||c==='\n')){row.push(cell.replace(/\r$/,''));cell='';if(c==='\n'){if(row.some(Boolean))rows.push(row);row=[];}}
  else cell+=c;
 }
 if(quoted)throw Error('Unclosed CSV quote');
 if(cell||row.length){row.push(cell.replace(/\r$/,''));rows.push(row);}
 return rows;
}
function buildCatalog(bytes,referenceDate){
 if(!/^\d{4}-\d{2}-\d{2}$/.test(referenceDate||''))throw Error('Provide the snapshot date as YYYY-MM-DD');
 // Anvisa publishes this dataset as Latin-1/Windows-1252, NOT UTF-8.
 const rows=parseCsv(new TextDecoder('windows-1252',{fatal:true}).decode(bytes));
 const header=rows.shift().map(x=>x.replace(/^\uFEFF/,''));
 for(const key of ['TIPO_PRODUTO','NOME_PRODUTO','PRINCIPIO_ATIVO','SITUACAO_REGISTRO','NUMERO_REGISTRO_PRODUTO','CLASSE_TERAPEUTICA','CATEGORIA_REGULATORIA'])if(!header.includes(key))throw Error('Missing column '+key);
 const idx=Object.fromEntries(header.map((x,i)=>[x,i])),groups=new Map();let activeRows=0,excludedMissingIdentity=0;
 for(const row of rows){
  if(row.length!==header.length)throw Error('Unexpected column count');
  const get=k=>clean(row[idx[k]]);
  if(get('TIPO_PRODUTO')!=='MEDICAMENTO'||get('SITUACAO_REGISTRO')!=='Ativo')continue;
  activeRows++;
  const name=get('NOME_PRODUTO'),ingredient=get('PRINCIPIO_ATIVO'),registration=get('NUMERO_REGISTRO_PRODUTO');
  if(!name||!ingredient||!registration||/^(null|nao informado|nao se aplica|n\/a|-)$/i.test(normalize(ingredient))){excludedMissingIdentity++;continue;}
  const key=normalize(name)+'\u0000'+normalize(ingredient);
  if(!groups.has(key))groups.set(key,{name,ingredient,registrations:new Set(),classes:new Set(),categories:new Set()});
  const item=groups.get(key);item.registrations.add(registration);if(get('CLASSE_TERAPEUTICA'))item.classes.add(get('CLASSE_TERAPEUTICA'));if(get('CATEGORIA_REGULATORIA'))item.categories.add(get('CATEGORIA_REGULATORIA'));
 }
 const products=Array.from(groups.entries()).sort(([a],[b])=>a<b?-1:a>b?1:0).map(([key,x])=>({
  id:'anvisa-'+crypto.createHash('sha256').update(key).digest('hex').slice(0,20),
  nome:x.name.toLocaleLowerCase('pt-BR').replace(/^\p{L}/u,c=>c.toLocaleUpperCase('pt-BR')),
  principioAtivo:x.ingredient,registros:Array.from(x.registrations).sort(),
  classes:Array.from(x.classes).sort(),categorias:Array.from(x.categories).sort()
 }));
 return {metadata:{fonte:SOURCE_URL,extraidoEm:referenceDate,sha256:crypto.createHash('sha256').update(bytes).digest('hex'),encoding:'windows-1252',linhasOrigem:rows.length,linhasAtivas:activeRows,excluidasSemIdentidade:excludedMissingIdentity,produtos:products.length,criterio:'MEDICAMENTO + Ativo + nome, princípio ativo e registro preenchidos; deduplicação por nome e campo de princípio ativo completos. O campo de princípios ativos NÃO é decomposto em associações ou alternativas.'},products};
}
function serialize(catalog){return '/* Generated by tools/import_medication_catalog.cjs. Source and hash below. Do not hand-edit. */\nglobalThis.KineSysMedicamentosAnvisa={\n"metadata":'+JSON.stringify(catalog.metadata)+',\n"products":[\n'+catalog.products.map(p=>JSON.stringify(p)).join(',\n')+'\n]};\n';}
if(require.main===module){
 const [input,date,output]=process.argv.slice(2);if(!input||!output)throw Error('Usage: node tools/import_medication_catalog.cjs source.csv YYYY-MM-DD output.js');
 const catalog=buildCatalog(fs.readFileSync(input),date);fs.writeFileSync(output,serialize(catalog));console.log(JSON.stringify(catalog.metadata));
}
module.exports={buildCatalog,serialize,parseCsv};
